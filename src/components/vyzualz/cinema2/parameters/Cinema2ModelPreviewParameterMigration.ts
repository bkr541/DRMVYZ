const mappingSlot = /^audio-map(?:[1-9]|1[0-2])-(?:enabled|source|target|intensity|min|max|curve|attack|release|smoothing|invert|quantize)$/
export function isRetiredCinema2ModelPreviewParameter(presetId: string, revision: number, key: string): boolean {
  const kind = /^drmvyz\.cinema2\.user-model-(form|shatter|dust|hologram|slices|voxel)$/.exec(presetId)?.[1]
  if (!kind || revision !== 1) return false
  const prefix = `user-model-${kind}-`
  if (!key.startsWith(prefix)) return false
  const property = key.slice(prefix.length)
  return legacyProperties.has(property) || mappingSlot.test(property)
}
