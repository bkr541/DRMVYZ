const decodedMasks = new Map<string, Uint8Array>()

function decodeMask(componentId: PixGridNeonMarqueeComponentId, frameId: PixGridNeonMarqueeFrameId): Uint8Array {
  const key = `${componentId}:${frameId}`
  const cached = decodedMasks.get(key)
  if (cached) return cached

  const binary = atob(ENCODED_MASK_BY_COMPONENT[componentId][frameId].replace(/\s+/g, ''))
  if (binary.length !== EXPECTED_MASK_BYTE_LENGTH) {
    throw new Error(`Invalid PixGrid neon marquee mask byte length ${binary.length}; expected ${EXPECTED_MASK_BYTE_LENGTH}.`)
  }
  const bytes = new Uint8Array(binary.length)
  for (let index = 0; index < binary.length; index += 1) bytes[index] = binary.charCodeAt(index)
  decodedMasks.set(key, bytes)
  return bytes
}

function normalizedFrameIndex(frameIndex: number): number {
  const count = PIX_GRID_NEON_MARQUEE_FRAME_ORDER.length
  return ((Math.floor(frameIndex) % count) + count) % count
}

export function getPixGridNeonMarqueeComponentMask(
  componentId: PixGridNeonMarqueeComponentId,
  frameIndex: number,
): Uint8Array {
  const frame = PIX_GRID_NEON_MARQUEE_FRAME_ORDER[normalizedFrameIndex(frameIndex)]
  return decodeMask(componentId, frame.id)
}

export function pixGridNeonMarqueeComponentContainsCell(
  componentId: PixGridNeonMarqueeComponentId,
  frameIndex: number,
  x: number,
  y: number,
): boolean {
  if (
    !Number.isInteger(x)
    || !Number.isInteger(y)
    || x < 0
    || x >= PIX_GRID_NEON_MARQUEE_FRAME_WIDTH
    || y < 0
    || y >= PIX_GRID_NEON_MARQUEE_FRAME_HEIGHT
  ) return false
  const index = y * PIX_GRID_NEON_MARQUEE_FRAME_WIDTH + x
  const mask = getPixGridNeonMarqueeComponentMask(componentId, frameIndex)
  return (mask[index >> 3] & (1 << (index & 7))) !== 0
}

