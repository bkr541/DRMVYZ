// Phase-1 portrait asset. MakeHuman hm08 source is CC0; see sources/makehuman/README.md.
import { readFileSync, writeFileSync } from 'node:fs'
import { gunzipSync } from 'node:zlib'
import { createHash } from 'node:crypto'
import { MeshoptSimplifier } from 'meshoptimizer'
const source='scripts/cinema2-assets/sources/makehuman/base.obj.gz'
const bytes=readFileSync(source),positions=[],groups=new Map();let group=''
for(const line of gunzipSync(bytes).toString('utf8').split('\n')){
 if(line.startsWith('v '))positions.push(line.trim().split(/\s+/).slice(1).map(Number))
 else if(line.startsWith('g ')){group=line.slice(2).trim();if(!groups.has(group))groups.set(group,[])}
 else if(line.startsWith('f '))groups.get(group)?.push(line.trim().split(/\s+/).slice(1).map(v=>parseInt(v,10)-1))
}
// Registered portrait coordinates: eye line .22, crown ~1.21, chin ~-.95; +Z toward viewer.
const place=p=>[p[0]*.9,p[1]<6.1 ? -.940516+(p[1]-6.1)*.38 : (p[1]-7.2842)*(p[1]>7.2842?.82:.98)+.22,(p[2]-.6)*.9]
const triangles=[]
for(const face of groups.get('body')){
 const center=face.reduce((s,i)=>s+positions[i][1],0)/face.length
 if(center<4.8)continue
 for(let i=1;i<face.length-1;i++)triangles.push(face[0],face[i],face[i+1])
}
const ids=[...new Set(triangles)],remap=new Map(ids.map((v,i)=>[v,i]))
const verts=new Float32Array(ids.flatMap(i=>place(positions[i])))
await MeshoptSimplifier.ready
const [reduced]=MeshoptSimplifier.simplify(new Uint32Array(triangles.map(i=>remap.get(i))),verts,3,2100*3,.5,['Regularize'])
const flat=new Float32Array([...reduced].flatMap(i=>[verts[i*3],verts[i*3+1],verts[i*3+2]]))
const eyes=['helper-r-eye','helper-l-eye'].map(name=>{
 const points=[...new Set(groups.get(name).flat())].map(i=>positions[i]);const center=[0,1,2].map(k=>points.reduce((s,p)=>s+p[k],0)/points.length)
 const radius=Math.max(...points.map(p=>Math.hypot(...p.map((v,k)=>v-center[k]))))
 return {center:place([center[0],center[1],center[2]+radius*.91]),radius:radius*.9*.62}
})
const metadata={source,sourceSha256:createHash('sha256').update(bytes).digest('hex'),license:'CC0-1.0',sourceNotice:'MakeHuman hm08; Data Collection AB, Joel Palmius, Jonas Hauquier. See sources/makehuman/README.md.',triangles:flat.length/9,eyes}
const encoded=Buffer.from(flat.buffer).toString('base64')
writeFileSync('src/components/vyzualz/cinema2/modules/switchIt/Cinema2SwitchItHuman.generated.ts',`// Generated by scripts/cinema2-assets/generate-switch-it-human.mjs; do not edit.\n// MakeHuman hm08 CC0 source; original portrait extraction/normalization.\nexport const SWITCH_IT_HUMAN_METADATA = ${JSON.stringify(metadata)} as const\nexport const SWITCH_IT_HUMAN_POSITIONS = '${encoded}'\n`)
console.log(JSON.stringify(metadata,null,2))
